#!/usr/bin/env node
// Generated knowledge only. Newly registered IPC commands are NOT executable
// by the AI without a separately reviewed, typed adapter.
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const rust=join(root,'apps/desktop/src-tauri/src');
const migrations=join(root,'crates/cpobras-storage/migrations');
const destination=join(root,'apps/desktop/src/services/ai-native-inventory.generated.js');
const read=file=>readFileSync(file,'utf8');
const handler=read(join(rust,'lib.rs'));
const permission=read(join(root,'apps/desktop/src-tauri/permissions/workspace.toml'));
const allowedBlock=permission.match(/commands\.allow\s*=\s*\[([\s\S]*?)\]/)?.[1];
const handlerBlock=handler.match(/\.invoke_handler\s*\(\s*tauri::generate_handler!\s*\[([\s\S]*?)\]\s*\)/)?.[1];
if(!allowedBlock||!handlerBlock)throw Error('No se encontró el registro de handlers o permisos Tauri');
const allowed=new Set([...allowedBlock.matchAll(/"([a-z0-9_]+)"/g)].map(m=>m[1]));
const entries=[...handlerBlock.matchAll(/commands::([a-z0-9_]+)::([a-z0-9_]+)/g)].map(m=>({module:m[1],name:m[2]}));
const inspected=new Map();
const inputs=[handler,permission];
const native=entries.map(({module,name})=>{
 let source=inspected.get(module);
 if(!source){source=read(join(rust,'commands',module+'.rs'));inspected.set(module,source);inputs.push(source);}
 const signature=[...source.matchAll(/#\[tauri::command\]\s*pub(?:\([^)]*\))?\s+(?:async\s+)?fn\s+([a-z0-9_]+)\s*(?:<[^>]*>)?\s*\(([\s\S]*?)\)\s*->/g)].find(m=>m[1]===name);
 if(!signature)throw Error('Falta firma Tauri para '+module+'::'+name);
 const args=[...signature[2].matchAll(/(?:^|,)\s*([a-z_]+)\s*:\s*([^,\n]+)/g)]
  .filter(m=>!['db','backups','directory','session'].includes(m[1])).map(m=>m[1]);
 return {name,module,allowed:allowed.has(name),args};
}).sort((a,b)=>a.name.localeCompare(b.name));
const names=new Set(native.map(item=>item.name));
if(names.size!==native.length)throw Error('Handlers Tauri duplicados');
for(const name of allowed)if(!names.has(name))throw Error('Permiso sin handler nativo: '+name);

function splitColumns(text){
 const parts=[];let depth=0,start=0,quote='';
 for(let i=0;i<text.length;i++){
  const c=text[i];
  if(quote){if(c===quote&&text[i+1]===quote){i++;continue;}if(c===quote)quote='';continue;}
  if(c==='"'||c==="'"||c==='\x60'){quote=c;continue;}
  if(c==='(')depth++;else if(c===')')depth--;
  else if(c===','&&depth===0){parts.push(text.slice(start,i).trim());start=i+1;}
 }
 parts.push(text.slice(start).trim());return parts;
}
const tables=new Map();
for(const file of readdirSync(migrations).filter(f=>f.endsWith('.sql')).sort()){
 const sql=read(join(migrations,file)).replace(/--[^\n]*/g,'');inputs.push(sql);
 const pattern=/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?["\x60]?([a-z_][a-z0-9_]*)["\x60]?\s*\(/gi;
 let m;
 while((m=pattern.exec(sql))){
  let depth=1,quote='',index=pattern.lastIndex;
  for(;index<sql.length;index++){
   const c=sql[index];
   if(quote){if(c===quote&&sql[index+1]===quote){index++;continue;}if(c===quote)quote='';continue;}
   if(c==='"'||c==="'"||c==='\x60'){quote=c;continue;}
   if(c==='(')depth++;else if(c===')'){depth--;if(!depth)break;}
  }
  if(depth)throw Error('CREATE TABLE sin cerrar en '+file);
  const name=m[1],table=tables.get(name)||{name,columns:[],references:[]};
  const existing=new Set(table.columns.map(c=>c.name));
  const links=new Set(table.references);
  for(const item of splitColumns(sql.slice(pattern.lastIndex,index))){
   const ref=item.match(/\bREFERENCES\s+["\x60]?([a-z_][a-z0-9_]*)/i);
   if(ref)links.add(ref[1]);
   const col=item.match(/^["\x60]?([a-z_][a-z0-9_]*)["\x60]?\s+([a-z]+(?:\s*\([^)]*\))?)/i);
   if(col&&!/^(PRIMARY|FOREIGN|UNIQUE|CONSTRAINT|CHECK)$/i.test(col[1])&&!existing.has(col[1])){
    table.columns.push({name:col[1],type:col[2].toUpperCase()});existing.add(col[1]);
   }
  }
  table.references=[...links].sort();tables.set(name,table);pattern.lastIndex=index+1;
 }
 const additions=/ALTER\s+TABLE\s+["\x60]?([a-z_][a-z0-9_]*)["\x60]?\s+ADD\s+(?:COLUMN\s+)?["\x60]?([a-z_][a-z0-9_]*)["\x60]?\s+([a-z]+)/gi;
 while((m=additions.exec(sql))){
  const t=tables.get(m[1]);if(t&&!t.columns.some(c=>c.name===m[2]))t.columns.push({name:m[2],type:m[3].toUpperCase()});
 }
}
const inventory={
 version:createHash('sha256').update(inputs.join('\n--source--\n')).digest('hex').slice(0,16),
 source:'registered native handlers, Tauri permissions and SQLite migration definitions',
 native,
 tables:[...tables.values()].sort((a,b)=>a.name.localeCompare(b.name))
};
const generated='// GENERATED by tools/generate-ai-inventory.mjs; do not edit.\n'
 +'// Listing a capability does not authorize executing it from AI.\n'
 +'export const AI_NATIVE_INVENTORY = '+JSON.stringify(inventory,null,1)+';\n';
if(process.argv.includes('--check')){
 if(read(destination)!==generated){console.error('El inventario de IA está desactualizado: ejecutá node tools/generate-ai-inventory.mjs');process.exitCode=1;}
 else console.log('Inventario de IA sincronizado: '+native.length+' comandos, '+tables.size+' tablas');
}else{
 writeFileSync(destination,generated);
 console.log('Inventario de IA generado: '+native.length+' comandos, '+tables.size+' tablas');
}
